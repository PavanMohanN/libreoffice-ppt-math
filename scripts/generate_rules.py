#!/usr/bin/env python3
"""
Generator script for PowerPoint-Style Math AutoCorrect rules (Espanso).
Builds package.yml with collision-proof triggers and regex expansions.

Usage:
    python3 scripts/generate_rules.py                               # Writes to package.yml
    python3 scripts/generate_rules.py --install                     # Installs globally to Espanso match dir
    python3 scripts/generate_rules.py --install --libreoffice-only  # Scopes rules to LibreOffice only
"""

import argparse
import subprocess
from pathlib import Path

# 1. Word-boundary backslash commands (prevents prefix collisions like \in vs \infty)
GREEK_AND_OPERATORS = {
    # Greek Lowercase
    "\\alpha": "α", "\\beta": "β", "\\gamma": "γ", "\\delta": "δ",
    "\\epsilon": "ε", "\\zeta": "ζ", "\\eta": "η", "\\theta": "θ",
    "\\iota": "ι", "\\kappa": "κ", "\\lambda": "λ", "\\mu": "μ",
    "\\nu": "ν", "\\xi": "ξ", "\\pi": "π", "\\rho": "ρ",
    "\\sigma": "σ", "\\tau": "τ", "\\upsilon": "υ", "\\phi": "φ",
    "\\chi": "χ", "\\psi": "ψ", "\\omega": "ω",

    # Greek Uppercase
    "\\Gamma": "Γ", "\\Delta": "Δ", "\\Theta": "Θ", "\\Lambda": "Λ",
    "\\Xi": "Ξ", "\\Pi": "Π", "\\Sigma": "Σ", "\\Phi": "Φ",
    "\\Psi": "Ψ", "\\Omega": "Ω",

    # Operators & Calculus
    "\\pm": "±", "\\mp": "∓", "\\times": "×", "\\div": "÷",
    "\\cdot": "·", "\\ast": "∗", "\\neq": "≠", "\\leq": "≤",
    "\\geq": "≥", "\\approx": "≈", "\\equiv": "≡", "\\propto": "∝",
    "\\infty": "∞", "\\partial": "∂", "\\nabla": "∇", "\\degree": "°",
    "\\sqrt": "√", "\\cbrt": "∛", "\\sum": "∑", "\\prod": "∏",
    "\\int": "∫", "\\iint": "∬", "\\oint": "∮",

    # Logic, Sets, Number Systems & Arrows
    "\\forall": "∀", "\\exists": "∃", "\\in": "∈", "\\notin": "∉",
    "\\subset": "⊂", "\\subseteq": "⊆", "\\cup": "∪", "\\cap": "∩",
    "\\emptyset": "∅", "\\land": "∧", "\\lor": "∨", "\\neg": "¬",
    "\\therefore": "∴", "\\because": "∵",
    "\\R": "ℝ", "\\C": "ℂ", "\\N": "ℕ", "\\Z": "ℤ",
    "\\uparrow": "↑", "\\downarrow": "↓", "\\mapsto": "↦",
    "\\to": "→", "\\gets": "←", "\\leftrightarrow": "↔", "\\iff": "⇔",
}

# 2. Instant triggers (non-overlapping; trailing space prevents <- / <= preempting <-> / <=>)
INSTANT_TRIGGERS = {
    # Operators & Arrows
    "!=": "≠", "<= ": "≤ ", ">=": "≥", "~=": "≈",
    "<->": "↔", "->": "→", "<- ": "← ", "<=>": "⇔", "=>": "⇒",

    # Single-character Superscripts
    "^0": "⁰", "^1": "¹", "^2": "²", "^3": "³", "^4": "⁴",
    "^5": "⁵", "^6": "⁶", "^7": "⁷", "^8": "⁸", "^9": "⁹",
    "^n": "ⁿ", "^i": "ⁱ", "^+": "⁺", "^-": "⁻",

    # Single-character Subscripts
    "_0": "₀", "_1": "₁", "_2": "₂", "_3": "₃", "_4": "₄",
    "_5": "₅", "_6": "₆", "_7": "₇", "_8": "₈", "_9": "₉",
    "_n": "ₙ", "_i": "ᵢ", "_x": "ₓ", "_+": "₊", "_-": "₋",
}

# 3. Word-boundary fractions (prevents 1/20 -> ½0 or 11/2 -> 1½)
WORD_FRACTIONS = {
    "1/2": "½", "1/3": "⅓", "2/3": "⅔", "1/4": "¼", "3/4": "¾",
}

# 4. Regex rules for multi-character super/subscripts & accents
REGEX_RULES_YAML = """  # ==========================================
  # REGEX: MULTI-CHARACTER SUPER/SUBSCRIPTS & ACCENTS
  # ==========================================
  - regex: "\\\\^\\\\{(?P<exp>[0-9a-pr-zABDEGHIJKLMNOPRTUVW+\\\\-=()]+)\\\\}"
    replace: "{{output}}"
    vars:
      - name: output
        type: script
        params:
          args:
            - python3
            - -c
            - |
              import os
              m = str.maketrans("0123456789+-=()abcdefghijklmnoprstuvwxyzABDEGHIJKLMNOPRTUVW", "⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻⁼⁽⁾ᵃᵇᶜᵈᵉᶠᵍʰⁱʲᵏˡᵐⁿᵒᵖʳˢᵗᵘᵛʷˣʸᶻᴬᴮᴰᴱᴳᴴᴵᴶᴷᴸᴹᴺᴼᴾᴿᵀᵁⱽᵂ")
              print(os.environ["ESPANSO_EXP"].translate(m), end="")

  - regex: "_\\\\{(?P<sub>[0-9aehijklmnoprstuvx+\\\\-=()]+)\\\\}"
    replace: "{{output}}"
    vars:
      - name: output
        type: script
        params:
          args:
            - python3
            - -c
            - |
              import os
              m = str.maketrans("0123456789+-=()aehijklmnoprstuvx", "₀₁₂₃₄₅₆₇₈₉₊₋₌₍₎ₐₑₕᵢⱼₖₗₘₙₒₚᵣₛₜᵤᵥₓ")
              print(os.environ["ESPANSO_SUB"].translate(m), end="")

  - regex: "\\\\\\\\vec\\\\{(?P<v>[A-Za-z])\\\\}"
    replace: "{{v}}\\u20d7"

  - regex: "\\\\\\\\bar\\\\{(?P<b>[A-Za-z])\\\\}"
    replace: "{{b}}\\u0304"

  - regex: "\\\\\\\\hat\\\\{(?P<h>[A-Za-z])\\\\}"
    replace: "{{h}}\\u0302"

  - regex: "\\\\\\\\tilde\\\\{(?P<t>[A-Za-z])\\\\}"
    replace: "{{t}}\\u0303"
"""

LIBREOFFICE_FILTER_YAML = """# Auto-generated by scripts/generate_rules.py
# Restricts PowerPoint-Style Math rules to LibreOffice only.

filter_exec: "soffice.bin"
extra_includes:
  - "../match/_ppt_math.yml"
"""


def get_espanso_base_dir() -> Path:
    """Detect Espanso's config directory cross-platform via `espanso path`."""
    try:
        res = subprocess.run(
            ["espanso", "path", "config"],
            capture_output=True,
            text=True,
            check=True,
        )
        detected = res.stdout.strip()
        if detected:
            return Path(detected)
    except (FileNotFoundError, subprocess.CalledProcessError):
        pass
    return Path.home() / ".config" / "espanso"


def generate_yaml(output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by scripts/generate_rules.py\n")
        f.write("# PowerPoint-Style Math AutoCorrect for Espanso\n\n")
        f.write("matches:\n")

        f.write("  # ==========================================\n")
        f.write("  # WORD-BOUNDARY BACKSLASH COMMANDS\n")
        f.write("  # ==========================================\n")
        for trig, rep in GREEK_AND_OPERATORS.items():
            t_esc = trig.replace("\\", "\\\\")
            f.write(f'  - trigger: "{t_esc}"\n')
            f.write(f'    replace: "{rep}"\n')
            f.write("    word: true\n")

        f.write("\n  # ==========================================\n")
        f.write("  # INSTANT OPERATORS, ARROWS & SUPER/SUBSCRIPTS\n")
        f.write("  # ==========================================\n")
        for trig, rep in INSTANT_TRIGGERS.items():
            f.write(f'  - trigger: "{trig}"\n')
            f.write(f'    replace: "{rep}"\n')

        f.write("\n  # ==========================================\n")
        f.write("  # WORD-BOUNDARY FRACTIONS\n")
        f.write("  # ==========================================\n")
        for trig, rep in WORD_FRACTIONS.items():
            f.write(f'  - trigger: "{trig}"\n')
            f.write(f'    replace: "{rep}"\n')
            f.write("    word: true\n")

        f.write("\n")
        f.write(REGEX_RULES_YAML)

    total = len(GREEK_AND_OPERATORS) + len(INSTANT_TRIGGERS) + len(WORD_FRACTIONS) + 6
    print(f"Successfully generated {output_path} ({total} rules).")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Espanso PowerPoint Math rules.")
    parser.add_argument(
        "--install",
        action="store_true",
        help="Write directly to your Espanso configuration directory.",
    )
    parser.add_argument(
        "--libreoffice-only",
        action="store_true",
        help="Scope rules to LibreOffice only (uses Espanso app-specific config).",
    )
    args = parser.parse_args()

    if args.install:
        base_dir = get_espanso_base_dir()
        if args.libreoffice_only:
            match_target = base_dir / "match" / "_ppt_math.yml"
            filter_target = base_dir / "config" / "libreoffice_math.yml"
            generate_yaml(match_target)
            filter_target.parent.mkdir(parents=True, exist_ok=True)
            filter_target.write_text(LIBREOFFICE_FILTER_YAML, encoding="utf-8")
            print(f"Created LibreOffice-only filter at {filter_target}.")
        else:
            generate_yaml(base_dir / "match" / "ppt_math.yml")
    else:
        repo_root = Path(__file__).resolve().parent.parent
        if args.libreoffice_only:
            generate_yaml(repo_root / "config" / "_ppt_math.yml")
            filter_target = repo_root / "config" / "libreoffice_math.yml"
            filter_target.write_text(LIBREOFFICE_FILTER_YAML, encoding="utf-8")
            print(f"Created LibreOffice-only filter at {filter_target}.")
        else:
            generate_yaml(repo_root / "package.yml")


if __name__ == "__main__":
    main()
