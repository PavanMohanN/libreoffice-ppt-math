#!/usr/bin/env python3
"""
Generator script for PowerPoint-Style Math AutoCorrect rules (Espanso).
Builds config/ppt_math.yml with collision-proof triggers and regex expansions.

Usage:
    python3 scripts/generate_rules.py            # Writes to config/ppt_math.yml
    python3 scripts/generate_rules.py --install  # Writes directly to ~/.config/espanso/match/ppt_math.yml
"""

import argparse
import os
from pathlib import Path

# 1. Word-boundary backslash commands (prevents prefix collisions like \in vs \infty)
GREEK_AND_OPERATORS = {
    # Greek Lowercase
    "\\alpha": "α", "\\beta": "β", "\\gamma": "γ", "\\delta": "δ",
    "\\epsilon": "ε", "\\zeta": "ζ", "\\eta": "η", "\\theta": "θ",
    "\\iota": "ι", "\\kappa": "κ", "\\lambda": "λ", "\\mu": "μ",
    "\\nu": "ν", "\\xi": "ξ", "\\pi": "π", "\\rho": "ρ",
    "\\sigma": "σ", "\\tau": "τ", "\\upsilon": "υ", "\\phi": "φ",
    "\\chi": "χ", "\\psi": "ψ", "\\omega": "ω",

    # Greek Uppercase
    "\\Gamma": "Γ", "\\Delta": "Δ", "\\Theta": "Θ", "\\Lambda": "Λ",
    "\\Xi": "Ξ", "\\Pi": "Π", "\\Sigma": "Σ", "\\Phi": "Φ",
    "\\Psi": "Ψ", "\\Omega": "Ω",

    # Operators & Calculus
    "\\pm": "±", "\\mp": "∓", "\\times": "×", "\\div": "÷",
    "\\cdot": "·", "\\ast": "∗", "\\neq": "≠", "\\leq": "≤",
    "\\geq": "≥", "\\approx": "≈", "\\equiv": "≡", "\\propto": "∝",
    "\\infty": "∞", "\\partial": "∂", "\\nabla": "∇",
    "\\sqrt": "√", "\\cbrt": "∛", "\\sum": "∑", "\\prod": "∏",
    "\\int": "∫", "\\iint": "∬", "\\oint": "∮",

    # Logic, Sets & Arrows
    "\\forall": "∀", "\\exists": "∃", "\\in": "∈", "\\notin": "∉",
    "\\subset": "⊂", "\\subseteq": "⊆", "\\cup": "∪", "\\cap": "∩",
    "\\emptyset": "∅", "\\land": "∧", "\\lor": "∨", "\\neg": "¬",
    "\\therefore": "∴", "\\because": "∵",
    "\\uparrow": "↑", "\\downarrow": "↓", "\\mapsto": "↦",
}

# 2. Instant triggers (fire immediately without needing Space)
INSTANT_TRIGGERS = {
    # Operators & Arrows
    "!=": "≠", "<=": "≤", ">=": "≥", "~=": "≈",
    "<->": "↔", "->": "→", "<-": "←", "<=>": "⇔", "=>": "⇒",

    # Common Fractions
    "1/2": "½", "1/3": "⅓", "2/3": "⅔", "1/4": "¼", "3/4": "¾",

    # Single-character Superscripts
    "^0": "⁰", "^1": "¹", "^2": "²", "^3": "³", "^4": "⁴",
    "^5": "⁵", "^6": "⁶", "^7": "⁷", "^8": "⁸", "^9": "⁹",
    "^n": "ⁿ", "^i": "ⁱ", "^+": "⁺", "^-": "⁻",

    # Single-character Subscripts
    "_0": "₀", "_1": "₁", "_2": "₂", "_3": "₃", "_4": "₄",
    "_5": "₅", "_6": "₆", "_7": "₇", "_8": "₈", "_9": "₉",
    "_n": "ₙ", "_i": "ᵢ", "_x": "ₓ", "_+": "₊", "_-": "₋",
}

# 3. Regex rules for multi-character super/subscripts & vector/bar accents
REGEX_RULES_YAML = """  # ==========================================
  # REGEX: MULTI-CHARACTER SUPER/SUBSCRIPTS & ACCENTS
  # ==========================================
  - regex: "\\\\^\\\\{(?P<exp>[0-9a-zA-Z+\\\\-=()]+)\\\\}"
    replace: "{{output}}"
    vars:
      - name: output
        type: script
        params:
          args:
            - python3
            - -c
            - |
              import os
              m = str.maketrans("0123456789+-=()abcdefghijklmnoprstuvwxyzABDEGHIJKLMNOPRTUVW", "⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻⁼⁽⁾ᵃᵇᶜᵈᵉᶠᵍʰⁱʲᵏˡᵐⁿᵒᵖʳˢᵗᵘᵛʷˣʸᶻᴬᴮᴰᴱᴳᴴᴵᴶᴷᴸᴹᴺᴼᴾᴿᵀᵁⱽᵂ")
              print(os.environ["ESPANSO_EXP"].translate(m), end="")

  - regex: "_\\\\{(?P<sub>[0-9aehijklmnoprstuvx+\\\\-=()]+)\\\\}"
    replace: "{{output}}"
    vars:
      - name: output
        type: script
        params:
          args:
            - python3
            - -c
            - |
              import os
              m = str.maketrans("0123456789+-=()aehijklmnoprstuvx", "₀₁₂₃₄₅₆₇₈₉₊₋₌₍₎ₐₑₕᵢⱼₖₗₘₙₒₚᵣₛₜᵤᵥₓ")
              print(os.environ["ESPANSO_SUB"].translate(m), end="")

  - regex: "\\\\\\\\vec\\\\{(?P<v>[A-Za-z])\\\\}"
    replace: "{{v}}\\u20d7"

  - regex: "\\\\\\\\bar\\\\{(?P<b>[A-Za-z])\\\\}"
    replace: "{{b}}\\u0304"
"""


def generate_yaml(output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by scripts/generate_rules.py\n")
        f.write("# PowerPoint-Style Math AutoCorrect for Espanso\n\n")
        f.write("matches:\n")

        f.write("  # ==========================================\n")
        f.write("  # WORD-BOUNDARY BACKSLASH COMMANDS\n")
        f.write("  # ==========================================\n")
        for trig, rep in GREEK_AND_OPERATORS.items():
            t_esc = trig.replace("\\", "\\\\")
            f.write(f'  - trigger: "{t_esc}"\n')
            f.write(f'    replace: "{rep}"\n')
            f.write("    word: true\n")

        f.write("\n  # ==========================================\n")
        f.write("  # INSTANT OPERATORS, ARROWS & SUPER/SUBSCRIPTS\n")
        f.write("  # ==========================================\n")
        for trig, rep in INSTANT_TRIGGERS.items():
            f.write(f'  - trigger: "{trig}"\n')
            f.write(f'    replace: "{rep}"\n')

        f.write("\n")
        f.write(REGEX_RULES_YAML)

    total = len(GREEK_AND_OPERATORS) + len(INSTANT_TRIGGERS) + 4
    print(f"Successfully generated {output_path} ({total} rules).")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Espanso PowerPoint Math rules.")
    parser.add_argument(
        "--install",
        action="store_true",
        help="Write directly to ~/.config/espanso/match/ppt_math.yml",
    )
    args = parser.parse_args()

    if args.install:
        target = Path.home() / ".config" / "espanso" / "match" / "ppt_math.yml"
    else:
        repo_root = Path(__file__).resolve().parent.parent
        target = repo_root / "config" / "ppt_math.yml"

    generate_yaml(target)


if __name__ == "__main__":
    main()
